"""Tests for the IDE type stub generator."""

from __future__ import annotations

import pandas as pd
import pytest

from dfmacro.ide import generate_type_stub


@pytest.fixture
def df():
    return pd.DataFrame(
        {
            "price": [50, 150],
            "category": ["books", "electronics"],
            "date": pd.to_datetime(["2024-01-01", "2024-01-02"]),
        }
    )


def test_generate_type_stub(df):
    stub = generate_type_stub(df)

    # Check if the header is there
    assert "Auto-generated by dfmacro" in stub
    assert "import datetime" in stub

    # Check if all columns are present and correctly typed
    assert "price: Series" in stub
    assert "category: Series" in stub
    assert "date: Series" in stub
