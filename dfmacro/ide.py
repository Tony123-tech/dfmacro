"""IDE Type Hints generator for dfmacro.

This module scans a DataFrame's schema and generates a .pyi stub file.
This allows VS Code / Pylance to provide perfect autocomplete for
bare column names like `price` and `category`.
"""

from __future__ import annotations

from typing import Any


def generate_type_stub(
    df: Any, module_name: str = "pandas", class_name: str = "Series"
) -> str:
    """Generate a Python .pyi stub string for the given DataFrame."""

    # Map pandas/polars dtypes to Python types
    type_mapping = {
        "int64": "int",
        "int32": "int",
        "float64": "float",
        "float32": "float",
        "object": "str",
        "string": "str",
        "bool": "bool",
        "datetime64[ns]": "datetime.datetime",
    }

    # Header
    stub = '"""Auto-generated by dfmacro for IDE autocompletion."""\n'
    stub += "from __future__ import annotations\n"
    stub += "import datetime\n"
    stub += f"from {module_name} import {class_name}\n\n"

    # Generate the column definitions
    stub += "# DataFrame Columns\n"
    for col in df.columns:
        # Try to get the dtype from pandas or polars
        if hasattr(df, "dtypes"):
            dtype_str = str(df.dtypes[col])
        else:
            dtype_str = str(df.schema[col])

        type_mapping.get(dtype_str, "Any")
        stub += f"{col}: {class_name}\n"

    # Optionally, we could generate a dummy function signature
    stub += "\n# Dummy function to mimic dfmacro.enable\n"
    stub += "def __getattr__(name: str) -> Any: ...\n"

    return stub


def write_stub_to_file(df: Any, filepath: str) -> None:
    """Generate and write the stub file to disk."""
    stub_content = generate_type_stub(df)
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(stub_content)
    print(f"✅ IDE Type Stub successfully generated at: {filepath}")
